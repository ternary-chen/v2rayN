using System.Text.Json.Nodes;

namespace AdaptiveRouting;

/// <summary>Community proxy matches use the dedicated exit. Manual and AI rules
/// are inserted afterwards at higher priority. Unknown web traffic may learn.</summary>
public static class XrayCommunityPolicyConfig
{
    public static string Apply(string json, bool learning)
    {
        var root = JsonNode.Parse(json)!.AsObject();
        if (!root["outbounds"]!.AsArray().Any(x => x?["tag"]?.ToString() == XrayAiPolicyConfig.OutboundTag))
            throw new InvalidOperationException("社区代理名单需要有效的专线节点；不会自动改走默认代理。");
        var original = root["routing"]!["rules"]!.AsArray();
        var infrastructure = new List<JsonNode>();
        var dedicated = new List<JsonNode>();
        var remaining = new List<JsonNode>();
        foreach (var value in original)
        {
            var rule = value!.DeepClone().AsObject();
            if (XrayLearningConfig.IsTerminal(rule)) continue;
            // An all-address terminal is also generated by IPIfNonMatch presets.
            if (rule["ip"] is JsonArray ips && ips.Count == 2 &&
                ips.Any(x => x!.ToString() == "0.0.0.0/0") && ips.Any(x => x!.ToString() == "::/0") &&
                !rule.Any(x => x.Value != null && x.Key is not ("ip" or "type" or "outboundTag" or "ruleTag"))) continue;
            if (rule["inboundTag"] != null || rule["outboundTag"]?.ToString() is "block" or "blocked" ||
                rule["outboundTag"]?.ToString() == "dns-out") infrastructure.Add(rule);
            else if (rule["outboundTag"]?.ToString() == "proxy")
            {
                rule["outboundTag"] = XrayAiPolicyConfig.OutboundTag;
                rule["ruleTag"] = "community-dedicated-" + (dedicated.Count + 1);
                dedicated.Add(rule);
            }
            else remaining.Add(rule);
        }
        var rules = new JsonArray();
        foreach (var r in infrastructure.Concat(dedicated)) rules.Add(r);
        rules.Add(new JsonObject { ["type"] = "field", ["ruleTag"] = "community-mainland", ["domain"] = new JsonArray("geosite:cn"), ["outboundTag"] = "direct" });
        rules.Add(new JsonObject { ["type"] = "field", ["ruleTag"] = "community-lan", ["ip"] = new JsonArray("geoip:private"), ["outboundTag"] = "direct" });
        foreach (var r in remaining) rules.Add(r);
        rules.Add(new JsonObject { ["type"] = "field", ["ruleTag"] = "community-fallback", ["network"] = "tcp,udp", ["outboundTag"] = learning ? "direct" : "proxy" });
        root["routing"]!["rules"] = rules;
        return root.ToJsonString();
    }
}
